		computed: {



		},
		components: {
		},
		created() {
			this.ruleForm.baomingshijian = this.getCurDateTime()
		},
		methods: {
			// 下载
			download(file){
				window.open(`${file}`)
			},
			// 初始化
			init(id,type) {
				if (id) {
					this.id = id;
					this.type = type;
				}
				if(this.type=='info'||this.type=='else'||this.type=='msg'){
					this.info(id);
				}else if(this.type=='logistics'){
					for(let x in this.ro) {
						this.ro[x] = true
					}
					this.logistics=false;
					this.info(id);
				}else if(this.type=='cross'){
					var obj = this.$storage.getObj('crossObj');
					for (var o in obj){
						if(o=='baomingbianhao'){
							this.ruleForm.baomingbianhao = obj[o];
							this.ro.baomingbianhao = true;
							continue;
						}
						if(o=='huodongmingcheng'){
							this.ruleForm.huodongmingcheng = obj[o];
							this.ro.huodongmingcheng = true;
							continue;
						}
						if(o=='huodongtupian'){
							this.ruleForm.huodongtupian = obj[o];
							this.ro.huodongtupian = true;
							continue;
						}
						if(o=='huodongshijian'){
							this.ruleForm.huodongshijian = obj[o];
							this.ro.huodongshijian = true;
							continue;
						}
						if(o=='huodongdidian'){
							this.ruleForm.huodongdidian = obj[o];
							this.ro.huodongdidian = true;
							continue;
						}
						if(o=='jingjiren'){
							this.ruleForm.jingjiren = obj[o];
							this.ro.jingjiren = true;
							continue;
						}
						if(o=='shoujihao'){
							this.ruleForm.shoujihao = obj[o];
							this.ro.shoujihao = true;
							continue;
						}
						if(o=='fensizhanghao'){
							this.ruleForm.fensizhanghao = obj[o];
							this.ro.fensizhanghao = true;
							continue;
						}
						if(o=='fensixingming'){
							this.ruleForm.fensixingming = obj[o];
							this.ro.fensixingming = true;
							continue;
						}
						if(o=='baomingshijian'){
							this.ruleForm.baomingshijian = obj[o];
							this.ro.baomingshijian = true;
							continue;
						}
					}
				}
				// 获取用户信息
				this.$http({
					url: `${this.$storage.get('sessionTable')}/session`,
					method: "get"
				}).then(({ data }) => {
					if (data && data.code === 0) {
						var json = data.data;
						if(((json.jingjiren!=''&&json.jingjiren) || json.jingjiren==0) && this.$storage.get("role")!="管理员"){
							this.ruleForm.jingjiren = json.jingjiren
							this.ro.jingjiren = true;
						}
						if(((json.shoujihao!=''&&json.shoujihao) || json.shoujihao==0) && this.$storage.get("role")!="管理员"){
							this.ruleForm.shoujihao = json.shoujihao
							this.ro.shoujihao = true;
						}
						if(((json.fensizhanghao!=''&&json.fensizhanghao) || json.fensizhanghao==0) && this.$storage.get("role")!="管理员"){
							this.ruleForm.fensizhanghao = json.fensizhanghao
							this.ro.fensizhanghao = true;
						}
						if(((json.fensixingming!=''&&json.fensixingming) || json.fensixingming==0) && this.$storage.get("role")!="管理员"){
							this.ruleForm.fensixingming = json.fensixingming
							this.ro.fensixingming = true;
						}
					} else {
						this.$message.error(data.msg);
					}
				});
			
			},
			// 多级联动参数

			info(id) {
				this.$http({
					url: `huodongbaoming/info/${id}`,
					method: "get"
				}).then(({ data }) => {
					if (data && data.code === 0) {
						this.ruleForm = data.data;
						//解决前台上传图片后台不显示的问题
						let reg=new RegExp('../../../upload','g')//g代表全部
					} else {
						this.$message.error(data.msg);
					}
				});
			},

			// 提交
			async onSubmit() {
					if(this.ruleForm.baomingbianhao) {
						this.ruleForm.baomingbianhao = String(this.ruleForm.baomingbianhao)
					}
					if(this.ruleForm.huodongtupian!=null) {
						this.ruleForm.huodongtupian = this.ruleForm.huodongtupian.replace(new RegExp(this.$base.url,"g"),"");
					}
					var objcross = this.$storage.getObj('crossObj');
					await this.$refs["ruleForm"].validate(async valid => {
						if (valid) {
							if(this.type=='cross'){
								var statusColumnName = this.$storage.get('statusColumnName');
								var statusColumnValue = this.$storage.get('statusColumnValue');
								if(statusColumnName!='') {
									var obj = this.$storage.getObj('crossObj');
									if(statusColumnName && !statusColumnName.startsWith("[")) {
										for (var o in obj){
											if(o==statusColumnName){
												obj[o] = statusColumnValue;
											}
										}
										var table = this.$storage.get('crossTable');
										await this.$http({
											url: `${table}/update`,
											method: "post",
											data: obj
										}).then(({ data }) => {});
									}
								}
							}
							
							await this.$http({
								url: `huodongbaoming/${!this.ruleForm.id ? "save" : "update"}`,
								method: "post",
								data: this.ruleForm
							}).then(async ({ data }) => {
								if (data && data.code === 0) {
									this.$message({
										message: "操作成功",
										type: "success",
										duration: 1500,
										onClose: () => {
											this.parent.showFlag = true;
											this.parent.addOrUpdateFlag = false;
											this.parent.huodongbaomingCrossAddOrUpdateFlag = false;
											this.parent.search();
											this.parent.contentStyleChange();
										}
									});
								} else {
									this.$message.error(data.msg);
								}
							});
						}
					});
			},
			// 获取uuid
			getUUID () {
				return new Date().getTime();
			},
			// 返回
			back() {
				this.parent.showFlag = true;
				this.parent.addOrUpdateFlag = false;
				this.parent.huodongbaomingCrossAddOrUpdateFlag = false;
				this.parent.contentStyleChange();
			},
			huodongtupianUploadChange(fileUrls) {
				this.ruleForm.huodongtupian = fileUrls;
			},
		}
	};
</script>
