					baomingbianhao: this.getUUID(),
					huodongmingcheng: '',
					huodongtupian: '',
					huodongshijian: '',
					huodongdidian: '',
					jingjiren: '',
					shoujihao: '',
					fensizhanghao: '',
					fensixingming: '',
					baomingshijian: '',
					shhf: '',
				},

				rules: {
					baomingbianhao: [
					],
					huodongmingcheng: [
						{ required: true, message: '活动名称不能为空', trigger: 'blur' },
					],
					huodongtupian: [
					],
					huodongshijian: [
					],
					huodongdidian: [
					],
					jingjiren: [
					],
